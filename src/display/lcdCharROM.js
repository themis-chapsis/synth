const BLANK_ROWS = new Uint8Array(8);

/** code -> Uint8Array(8) of 5-bit rows, bit 4 = leftmost column. */
const rowCache = new Map();

/**
 * @param {number} code HD44780 character code 0-255
 * @returns {Uint8Array} 8 rows, 5 bits each (bit 4 = leftmost dot)
 */
export function glyphRows(code) {
  let rows = rowCache.get(code);
  if (rows) return rows;
  const cols = COL[code];
  if (!cols) return BLANK_ROWS;
  rows = new Uint8Array(8);
  for (let r = 0; r < 8; r++) {
    let bits = 0;
    for (let c = 0; c < 5; c++) {
      if (cols[c] & (1 << r)) bits |= 1 << (4 - c);
    }
    rows[r] = bits;
  }
  rowCache.set(code, rows);
  return rows;
}
